        const val THREE_GP = "video/3gpp"
        const val THREE_GPP = "video/3gpp"
        const val THREE_GPP2 = "video/3gpp2"
    }

    object Application {
        const val JSON = "application/json"
        const val PDF = "application/pdf"
        const val XML = "application/xml"
        const val RSS = "application/rss+xml"
        const val ATOM = "application/atom+xml"
        const val OGG = "application/ogg"

        const val MSWORD = "application/msword"
        const val EXCEL = "application/vnd.ms-excel"
