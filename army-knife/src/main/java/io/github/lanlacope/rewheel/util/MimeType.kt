    object Text {
        const val PLAIN = "text/plain"
        const val HTML = "text/html"
        const val CSS = "text/css"
        const val JAVASCRIPT = "text/javascript"
        const val XML = "text/xml"
        const val CSV = "text/csv"
    }

    object Image {
        const val PNG = "image/png"
        const val JPEG = "image/jpeg"
        const val GIF = "image/gif"
        const val BMP = "image/bmp"
        const val SVG = "image/svg+xml"
        const val WEBP = "image/webp"
        const val ICON = "image/x-icon"
    }

    object Audio {
        const val MP3 = "audio/mpeg"
        const val MP4 = "audio/mp4"
        const val WAV = "audio/wav"
        const val OGG = "audio/ogg"
        const val MIDI = "audio/midi"
        const val AIFF = "audio/aiff"
        const val WMA = "audio/x-ms-wma"
        const val FLAC = "audio/flac"
        const val AAC = "audio/aac"
        const val VORBIS = "audio/vorbis"
