        const val ALAC = "audio/x-realaudio"
    }

    object Video {
        const val MP3 = "video/mpeg"
        const val MP4 = "video/mp4"
        const val WEBM = "video/webm"
        const val OGG = "video/ogg"
        const val MOV = "video/quicktime"
        const val FLV = "video/x-flv"
        const val H264 = "video/h264"
        const val H265 = "video/h265"
        const val MKV = "video/x-matroska"
